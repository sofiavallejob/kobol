# Export the VCF model (SSM2040 + learned law) and the SSM2050 ADS to ../prototype/vcf.js
# (JS port of ../dsp/kobol_vcf.h, kobol_vcf_law.h, kobol_env_vca.h; checked against the C++ in check_js.py)
import numpy as np, json
W = np.load('law_mlp.npz'); PP = np.load('law_phys.npy'); O = np.load('oscfit.npy', allow_pickle=True).item()
M = sorted({k.split('_')[0] for k in W.files if k.startswith('m')})
law = dict(drive=float(O['drive']), q=float(O['q']), phys=PP.tolist(), SC=W['SC'].tolist(),
           nets=[{nm: np.round(W[f'{m}_{nm}'], 9).ravel().tolist() for nm in ['W0', 'b0', 'W1', 'b1', 'W2', 'b2']} for m in M])
js = '''// Kobol VCF (SSM2040 + control law learned from the RSF recordings) and SSM2050 ADS envelopes.
// GENERATED by vcf-model/export_js.py -- JS port of dsp/kobol_vcf.h, kobol_vcf_law.h, kobol_env_vca.h.
const KVCF=(function(){
  const LAW=%s;
  const H=LAW.nets[0].b0.length, sp=z=>z>30?z:Math.log1p(Math.exp(z));
  function law(vc,vr){            // volts (MCV24 scale) -> {fc Hz, K, gain dB}
    const p=LAW.phys;
    const y=[p[0]+p[1]*vc-sp(p[2]*(vc-p[3]))*p[4]/p[2], p[5]*sp(p[6]*(vr-p[7]))/p[6]+p[8]*vr*vc/10, p[9]+p[10]*vc+p[11]*vc*vc];
    const x0=(vc-5)/3,x1=(vr-5)/3,h1=new Float64Array(H),h2=new Float64Array(H);
    for(const n of LAW.nets){
      for(let j=0;j<H;j++)h1[j]=Math.tanh(x0*n.W0[j]+x1*n.W0[H+j]+n.b0[j]);
      for(let j=0;j<H;j++){let s=n.b1[j];for(let i=0;i<H;i++)s+=h1[i]*n.W1[i*H+j];h2[j]=Math.tanh(s);}
      for(let o=0;o<3;o++){let s=n.b2[o];for(let i=0;i<H;i++)s+=h2[i]*n.W2[i*3+o];y[o]+=s/LAW.SC[o]/LAW.nets.length;}
    }
    return {fc:1000*Math.pow(2,y[0]),K:Math.max(0,y[1]),gainDb:y[2]};
  }
  const sec=v=>{const a=v*v;return a<1e-6?1-a/3:Math.tanh(v)/v;};
  class SSM2040{                  // 4 OTA cells (tanh) + CA3080 resonance feedback, linearised ZDF/TPT
    constructor(fs){this.fs=fs;this.s=new Float64Array(4);this.v=new Float64Array(4);this.fb=0;this.it=2;this.q=LAW.q;}
    process(x,fc,K,drive,gain){
      fc=Math.min(fc,0.45*this.fs);const g=Math.tan(Math.PI*fc/this.fs),xin=drive*x,s=this.s,v=this.v,G=[0,0,0,0],yy=[0,0,0,0];let out=0;
      for(let it=0;it<this.it;it++){
        let a=1,b=0;
        for(let i=0;i<4;i++){const gt=g*sec(v[i]);G[i]=gt/(1+gt);b=G[i]*b+(1-G[i])*s[i];a*=G[i];}
        const Kt=K*sec(this.q*this.fb),u=(xin-Kt*b)/(1+Kt*a);let inp=u;
        for(let i=0;i<4;i++){yy[i]=G[i]*inp+(1-G[i])*s[i];v[i]=inp-yy[i];inp=yy[i];}
        this.fb=yy[3];
        if(it===this.it-1){for(let i=0;i<4;i++)s[i]=2*yy[i]-s[i];out=yy[3];}
      }
      return gain*out/drive;
    }
  }
  class SSM2050{                  // ADS: RC charge toward 1.3 x peak, decay to sustain, release = decay (or fast)
    constructor(fs){this.fs=fs;this.v=0;this.stage=0;this.gate=false;this.decayOn=true;}
    static time(k){return 1e-3*Math.pow(1e4,Math.min(1,Math.max(0,k)));}
    process(g,a,d,s){
      if(g&&!this.gate)this.stage=1; if(!g&&this.gate)this.stage=3; this.gate=g;
      const fs=this.fs,tA=SSM2050.time(a),tD=SSM2050.time(d);
      if(this.stage===1){this.v+=(1.3-this.v)*(1-Math.exp(-1/(tA*fs)));if(this.v>=1){this.v=1;this.stage=2;}}
      else if(this.stage===2)this.v+=(s-this.v)*(1-Math.exp(-1/(tD*fs)));
      else if(this.stage===3){this.v-=this.v*(1-Math.exp(-1/((this.decayOn?tD:2e-3)*fs)));if(this.v<1e-5){this.v=0;this.stage=0;}}
      return this.v;
    }
  }
  return {law,SSM2040,SSM2050,drive:LAW.drive,octPerV:LAW.phys[1]};
})();
if(typeof module!=='undefined')module.exports=KVCF;
''' % json.dumps(law, separators=(',', ':'))
open('../prototype/vcf.js', 'w').write(js); print('wrote ../prototype/vcf.js', len(js), 'bytes')
